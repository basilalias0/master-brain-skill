#!/usr/bin/env node
'use strict';
// law-lint.cjs caps <root> [--exempt FILE] | digest <LAWS> <DIGEST> | stamp <LAWS> <DIGEST> | digest-check <LAWS> <DIGEST>
// caps: .md 200 lines, .ts/.tsx 400, .js/.jsx/.cjs/.mjs 300. Exempt file: one path prefix per line.
// digest: GENERATES LAWS_DIGEST.md (30 lines or fewer: each law's number, bold title and first sentence) and stamps
//   it, so no model writes the digest by hand. stamp: only rewrites the source_hash line of an existing digest.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SKIP = new Set(['node_modules', '.git', '.next', 'dist', 'build', 'coverage', 'archive']);
const cap = (f) => (/\.md$/.test(f) ? 200 : /\.tsx?$/.test(f) ? 400 : /\.(?:[cm]?jsx?)$/.test(f) ? 300 : 0);
const lines = (f) => fs.readFileSync(f, 'utf8').split('\n').length - (fs.readFileSync(f, 'utf8').endsWith('\n') ? 1 : 0);
const sha = (f) => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');

function caps(root, exemptFile) {
  const ex = exemptFile && fs.existsSync(exemptFile)
    ? fs.readFileSync(exemptFile, 'utf8').split('\n').map((s) => s.trim()).filter((s) => s && !s.startsWith('#')) : [];
  const bad = [];
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      if (SKIP.has(e.name)) continue;
      const p = path.join(d, e.name);
      const rel = path.relative(root, p).replace(/\\/g, '/');
      if (ex.some((x) => rel === x || rel.startsWith(x.replace(/\/?$/, '/')))) continue;
      if (e.isDirectory()) walk(p);
      else { const c = cap(e.name); if (c) { const n = lines(p); if (n > c) bad.push(`${rel}: ${n} lines (cap ${c})`); } }
    }
  })(root);
  return bad;
}

function digestHash(digest) {
  const m = /^source_hash:\s*([0-9a-f]{64})\s*$/m.exec(fs.readFileSync(digest, 'utf8'));
  return m ? m[1] : null;
}

function stamp(laws, digest) {
  let s = fs.readFileSync(digest, 'utf8');
  const line = `source_hash: ${sha(laws)}`;
  s = /^source_hash:.*$/m.test(s) ? s.replace(/^source_hash:.*$/m, line) : s.replace(/^(# .*\n)/, `$1${line}\n`);
  fs.writeFileSync(digest, s);
}

// The laws under "## The laws": "N. **Title.** text", continuation lines indented. One line each:
// number, bold title, first sentence of the text after it (220 chars at most).
function laws(text) {
  const out = []; let on = false; let cur = null;
  for (const l of text.replace(/\r\n/g, '\n').split('\n')) {
    if (/^## /.test(l)) { on = /^## The laws/i.test(l); cur = null; continue; }
    if (!on) continue;
    const m = /^(\d+)\. (.*)$/.exec(l);
    if (m) { cur = { n: m[1], text: m[2] }; out.push(cur); } else if (cur && /^\s+\S/.test(l)) cur.text += ' ' + l.trim();
  }
  // First sentence: up to a "." that ends a word outside parentheses and backticks.
  const sentence = (s) => {
    let depth = 0; let tick = false;
    for (let i = 0; i < s.length; i++) {
      const c = s[i];
      if (c === '`') tick = !tick;
      else if (!tick && c === '(') depth++;
      else if (!tick && c === ')') depth = Math.max(0, depth - 1);
      else if (!tick && !depth && c === '.' && (i + 1 === s.length || /\s/.test(s[i + 1]))) return s.slice(0, i + 1);
    }
    return s;
  };
  return out.map(({ n, text }) => {
    const t = /^\*\*(.+?)\*\*\s*(.*)$/.exec(text);
    const title = t ? t[1].replace(/[.:,]$/, '') : '';
    const rest = (t ? t[2] : text).replace(/^[:.,]\s*/, '');
    const first = sentence(rest);
    const line = `${n}. ${title ? `**${title}.** ` : ''}${first}`.trim();
    return line.length > 220 ? line.slice(0, 217) + '...' : line;
  });
}

function digest(lawsFile, digestFile) {
  const ls = laws(fs.readFileSync(lawsFile, 'utf8')).slice(0, 27);
  const text = ['# LAWS_DIGEST (generated by law-lint.cjs digest; never edit by hand)', `source_hash: ${sha(lawsFile)}`,
    'One line per law; the full law in LAWS.md has the same number.', ...ls].join('\n') + '\n';
  fs.writeFileSync(digestFile, text);
  return ls.length;
}

if (require.main === module) {
  const [cmd, a, b] = process.argv.slice(2);
  if (cmd === 'caps') {
    const i = process.argv.indexOf('--exempt');
    const bad = caps(a || '.', i > 0 ? process.argv[i + 1] : null);
    if (bad.length) { console.log('law-lint: over cap\n' + bad.join('\n')); process.exit(1); }
    console.log('law-lint: ok');
  } else if (cmd === 'digest' && a && b) { console.log(`digest written: ${digest(a, b)} laws, stamped ${b}`);
  } else if (cmd === 'stamp' && a && b) { stamp(a, b); console.log('stamped ' + b);
  } else if (cmd === 'digest-check' && a && b) {
    const h = fs.existsSync(b) ? digestHash(b) : null;
    if (h !== sha(a)) { console.log('digest STALE: read the full LAWS.md, then run law-lint.cjs digest <LAWS> <DIGEST>'); process.exit(1); }
    console.log('digest ok');
  } else { console.error('usage: law-lint.cjs caps <root> [--exempt FILE] | digest|stamp|digest-check <LAWS> <DIGEST>'); process.exit(2); }
}

module.exports = { caps, stamp, digest, laws, digestHash, sha };
