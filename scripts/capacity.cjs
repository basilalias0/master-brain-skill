#!/usr/bin/env node
'use strict';
// capacity.cjs: chat capacity (law "Chat capacity"; owner, 2026-11-05). Zero model tokens.
//   calibrate <master_dir>          write <master_dir>/CAPACITY.md for THIS machine (RAM, logical cores)
//   check <master_dir>              recalibrate when CAPACITY.md is missing or the machine changed; silent otherwise
//   load <role> <ctx%> <task>... [--new <task>]
//        role: worker|master|chief. task: "score:hold:state", e.g. 6:sup:active
//        hold: do 1.0 | sub 0.6 | sup 0.5 (a worker chat) | master (Chief only: 1.5 flat) | lock (+1 flat: e2e/sweep/heavy lock)
//        state: active 1.0 | bg 0.5 | wait 0.2 | queued 0
// Why: not every machine has 16 GB, so the machine budget comes from the machine itself, at onboarding and at boot.
// Budget = max(4, min(floor(RAM GB) - 3, logical cores)): 3 GB stay for the OS, the browser and the app; heavy test
// runs are CPU-bound, so cores cap it too. 15.3 GB / 12 cores gives 12, the value calibrated on the 2026-09 to 11-05 history.
// Exit: 0 ok or fits, 1 full (load), 2 bad input. MB_SPEC='{"ramGB":8,"cores":4,"host":"x"}' overrides the machine (tests).
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');

const JOBS = [
  ['dev or production server (grows to ~4 GB); a test run that starts its own server counts it too', 4],
  ['full browser e2e run (Playwright or similar)', 4],
  ['full unit test run', 3],
  ['browser sweep or driver (checker, screenshots)', 2],
  ['type check', 1],
  ['static file server (artifact preview)', 0.5],
  ['each running chat', 0.25],
];
const LIMITS = { worker: 8, master: 12, chief: 10 };
const HARD = { worker: '1 job; at most 2 subagents', master: 'at most 4 worker chats running; at most 2 subagents (audits excepted)', chief: 'at most 2 subagents; no own build work' };
const HOLD = { do: 1, sub: 0.6, sup: 0.5 };
const STATE = { active: 1, bg: 0.5, wait: 0.2, queued: 0 };

function spec() {
  if (process.env.MB_SPEC) return JSON.parse(process.env.MB_SPEC);
  return { ramGB: +(os.totalmem() / 2 ** 30).toFixed(1), cores: os.cpus().length, host: os.hostname() };
}
function fingerprint(s) {
  const h = crypto.createHash('sha1').update(String(s.host || '')).digest('hex').slice(0, 8);
  return { ramGB: Math.round(s.ramGB * 2) / 2, cores: s.cores, host: h };
}
function budget(s) {
  return Math.max(4, Math.min(Math.floor(s.ramGB) - 3, s.cores));
}
function factor(ctx) {
  if (ctx >= 85) return 0;
  if (ctx >= 70) return 0.6;
  if (ctx >= 50) return 0.8;
  return 1;
}
const q = (x) => Math.round(x * 4) / 4;

function weight(task) {
  const [scoreS, hold, state] = String(task).split(':');
  const score = Number(scoreS);
  if (!(score >= 0 && score <= 10) || !(state in STATE)) throw new Error(`bad task "${task}" (score:hold:state)`);
  if (hold === 'master') return { task, hold, state, w: q(1.5 * STATE[state]) };
  if (hold === 'lock') return { task, hold, state, w: state === 'queued' ? 0 : 1 };
  if (!(hold in HOLD)) throw new Error(`bad hold "${hold}" in "${task}"`);
  return { task, hold, state, w: q((1 + score / 2) * HOLD[hold] * STATE[state]) };
}

function render(s, fp) {
  const b = budget(s);
  const low = b < 8 ? '\n- **Small machine:** a server plus a full e2e run does not fit. Stop the other servers before a heavy run.\n' : '\n';
  return `# Capacity for this machine (generated by \`scripts/capacity.cjs\`, ${new Date().toISOString().slice(0, 10)})

Do not edit by hand: \`node <skill>/scripts/capacity.cjs calibrate <master_dir>\` rewrites it, and \`check\` at boot redoes it when
the machine changes. Rule: LAWS.md "Chat capacity". Never commit this file.

## Machine: ${s.ramGB} GB RAM, ${s.cores} logical cores, so the budget is **${b} machine points**
Budget = max(4, min(floor(RAM GB) - 3, cores)). The heavy slot stays one at a time. A job that would pass the budget waits
for the slot and is never refused; the owner is told the wait.${low}
| Job | Points |
|---|---|
${JOBS.map(([j, p]) => `| ${j} | ${p} |`).join('\n')}

## Chat limits (attention, the same on every machine)
| Role | Limit | Hard caps |
|---|---|---|
${Object.keys(LIMITS).map((r) => `| ${r} | ${LIMITS[r]} | ${HARD[r]} |`).join('\n')}

Weight W = Size × Hold × State, Size = 1 + score/2 (the 0-10 effort score). Hold: do 1.0, subagent 0.6, worker chat 0.5,
a Master (Chief) 1.5 flat; +1 while holding an e2e, a sweep or the heavy lock. State: active 1.0, background 0.5,
waiting 0.2, queued 0. A task fits when L + W ≤ limit × F.

| Context used | under 50% | 50-70% | 70-85% | 85% or more |
|---|---|---|---|---|
| F | 1.0 | 0.8 | 0.6 | 0: take nothing new; write the LAST block, compact, go on |

<!-- capacity ${JSON.stringify({ ...fp, budget: b })} -->
`;
}

function calibrate(dir, quiet) {
  if (!dir || !fs.existsSync(dir)) throw new Error(`no master_dir "${dir}"`);
  const s = spec();
  const fp = fingerprint(s);
  fs.writeFileSync(path.join(dir, 'CAPACITY.md'), render(s, fp));
  const b = budget(s);
  if (!quiet) console.log(`capacity: ${s.ramGB} GB RAM, ${s.cores} cores, budget ${b} machine points (CAPACITY.md written)`);
  return b;
}

function check(dir) {
  const f = path.join(dir || '', 'CAPACITY.md');
  if (!fs.existsSync(f)) { calibrate(dir, true); return console.log(`capacity: calibrated for this machine, budget ${budget(spec())} (CAPACITY.md)`); }
  const m = fs.readFileSync(f, 'utf8').match(/<!-- capacity (\{.*\}) -->/);
  const now = fingerprint(spec());
  const old = m ? JSON.parse(m[1]) : {};
  if (old.ramGB !== now.ramGB || old.cores !== now.cores || old.host !== now.host) {
    calibrate(dir, true);
    console.log(`capacity: machine changed, recalibrated: budget ${budget(spec())} (was ${old.budget ?? 'unknown'})`);
  }
}

function load(role, ctxS, tasks, next) {
  if (!(role in LIMITS)) throw new Error(`bad role "${role}" (worker|master|chief)`);
  const ctx = Number(ctxS);
  if (!(ctx >= 0 && ctx <= 100)) throw new Error(`bad context % "${ctxS}"`);
  const ws = tasks.map(weight);
  const L = q(ws.reduce((a, t) => a + t.w, 0));
  const cap = q(LIMITS[role] * factor(ctx));
  const running = (h) => ws.filter((t) => t.hold === h && (t.state === 'active' || t.state === 'bg')).length;
  const broken = [];
  if (role === 'master' && running('sup') > 4) broken.push(`${running('sup')} worker chats running (cap 4)`);
  if (running('sub') > 2) broken.push(`${running('sub')} subagents (cap 2)`);
  if (role === 'worker' && running('do') > 1) broken.push(`${running('do')} jobs (cap 1)`);
  ws.forEach((t) => console.log(`  ${t.task.padEnd(16)} W ${t.w}`));
  console.log(`load ${L} / ${cap} (${role} limit ${LIMITS[role]} × F ${factor(ctx)} at ${ctx}% context)`);
  if (broken.length) console.log(`hard cap broken: ${broken.join('; ')}`);
  let full = L > cap || broken.length > 0;
  if (next) {
    const n = weight(next);
    const fits = !full && L + n.w <= cap;
    console.log(`new ${next}: W ${n.w}: ${fits ? 'take it' : 'FULL: reuse an idle worker, else needs-chip to the Chief'}`);
    full = !fits;
  } else console.log(full ? 'FULL: take nothing new (ladder: reuse an idle worker, else needs-chip)' : `room ${q(cap - L)}`);
  if (factor(ctx) === 0) console.log('context at 85%+: write the LAST block and BOARD, let it compact, then go on');
  return full ? 1 : 0;
}

if (require.main === module) {
  const [cmd, ...a] = process.argv.slice(2);
  try {
    if (cmd === 'calibrate') calibrate(a[0]);
    else if (cmd === 'check') check(a[0]);
    else if (cmd === 'load') {
      const i = a.indexOf('--new');
      const next = i >= 0 ? a[i + 1] : null;
      const rest = i >= 0 ? a.slice(0, i).concat(a.slice(i + 2)) : a;
      process.exit(load(rest[0], rest[1], rest.slice(2), next));
    } else { console.error('usage: capacity.cjs calibrate|check <master_dir> | load <role> <ctx%> <score:hold:state>... [--new <task>]'); process.exit(2); }
  } catch (e) { console.error(String(e.message || e)); process.exit(2); }
}
module.exports = { budget, factor, weight, fingerprint };
